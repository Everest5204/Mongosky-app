#!/usr/bin/env python3
"""Rebuild the native resources and legacy UI index; Python standard library only."""
import hashlib
import html
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
CATALOG = Path(__file__).with_name("catalog.json")
PLACEHOLDER = re.compile(r"%([1-9][0-9]*)\$s")


def read_catalog():
    rows = json.loads(CATALOG.read_text(encoding="utf-8"))
    sources, names = set(), set()
    for row in rows:
        en, bn = row["en"], row["bn"]
        if not en or en in sources:
            raise ValueError(f"Empty or duplicate English source: {en!r}")
        sources.add(en)
        if not re.search(r"[\u0980-\u09ff]", bn):
            raise ValueError(f"Missing Bangla translation: {en!r}")
        if en.count("Mongosky") != bn.count("Mongosky"):
            raise ValueError(f"Brand name changed: {en!r}")
        slots = set(PLACEHOLDER.findall(en))
        if slots != set(PLACEHOLDER.findall(bn)):
            raise ValueError(f"Placeholder mismatch: {en!r}")
        row["template"] = bool(slots)
        if "resource" not in row:
            slug = re.sub("[^a-z0-9]+", "_", en.lower()).strip("_")[:58] or "message"
            row["resource"] = "lang_" + slug + "_" + hashlib.sha256(en.encode()).hexdigest()[:7]
        name = row["resource"]
        if not re.fullmatch(r"[a-z][a-z0-9_]*", name) or name in names:
            raise ValueError(f"Invalid or duplicate Android resource: {name!r}")
        names.add(name)
    return rows


def xml_value(text, template):
    if template:
        text = PLACEHOLDER.sub(lambda m: "@@ARG" + m[1] + "@@", text).replace("%", "%%")
        text = re.sub(r"@@ARG(\d+)@@", lambda m: "%" + m[1] + "$s", text)
    text = text.replace("\\", "\\\\").replace("\n", "\\n").replace("'", "\\'").replace('"', '\\"')
    return "&quot;" + html.escape(text, quote=False) + "&quot;"


def kotlin(text):
    return json.dumps(text, ensure_ascii=False).replace("$", "\\$")


def generated_files(rows):
    result = {}
    for qualifier, language in [("values", "en"), ("values-bn", "bn")]:
        lines = ['<?xml version="1.0" encoding="utf-8"?>',
                 '<!-- Generated by tools/language/generate_catalog.py. -->', '<resources>']
        for row in rows:
            formatted = "" if row["template"] else ' formatted="false"'
            lines.append(f'    <string name="{row["resource"]}"{formatted}>'
                         f'{xml_value(row[language], row["template"])}</string>')
        lines.append("</resources>")
        result[f"app/src/main/res/{qualifier}/language_strings.xml"] = "\n".join(lines) + "\n"
    labels = [row for row in rows if not row["template"]]
    templates = sorted([row for row in rows if row["template"]],
                       key=lambda row: -len(PLACEHOLDER.sub("", row["en"])))
    lines = ["package com.mongosky.app.language", "", "import com.mongosky.app.R", "",
             "/** Generated index; edit tools/language/catalog.json, then run generate_catalog.py. */",
             "internal object LanguageCatalog {",
             "    val exact: Map<String, Int> by lazy(LazyThreadSafetyMode.PUBLICATION) {",
             "        buildMap {"]
    for index in range(0, len(labels), 120):
        lines.append(f"            putAll(labels{index // 120}())")
    lines += ["        }", "    }", "",
              "    val templates: List<LanguageTemplate> by lazy(LazyThreadSafetyMode.PUBLICATION) {",
              "        listOf("]
    for row in templates:
        lines.append(f'            LanguageTemplate({kotlin(row["en"])}, R.string.{row["resource"]}),')
    lines += ["        )", "    }"]
    for index in range(0, len(labels), 120):
        lines += ["", f"    private fun labels{index // 120}(): Map<String, Int> = mapOf("]
        for row in labels[index:index + 120]:
            lines.append(f'        {kotlin(row["en"])} to R.string.{row["resource"]},')
        lines.append("    )")
    lines.append("}")
    result["app/src/main/java/com/mongosky/app/language/LanguageCatalog.kt"] = "\n".join(lines) + "\n"
    return result


if __name__ == "__main__":
    rows = read_catalog()
    for relative, content in generated_files(rows).items():
        path = ROOT / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")
    CATALOG.write_text(json.dumps(rows, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Generated {len(rows)} English/Bangla resource pairs and their Kotlin index.")
